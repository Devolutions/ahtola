        TestName = "Aegis256_FlippedTag")]
    public void AegisRejectsSpecificationNegativeVector(
        byte cipherId,
        string key,
        string nonce,
        string associatedData,
        string ciphertext,
        string tag)
    {
        var cipher = (StorageCipher)cipherId;
        foreach (var software in new[] { false, true })
        {
            using var aead = AhtolaAeadFactory.Create(cipher, Convert.FromHexString(key), software);
            var ciphertextBytes = Convert.FromHexString(ciphertext);
            var plaintext = new byte[ciphertextBytes.Length];
            plaintext.AsSpan().Fill(0xCC);

            aead.TryDecrypt(
                    Convert.FromHexString(nonce),
                    ciphertextBytes,
                    Convert.FromHexString(tag),
                    plaintext,
                    Convert.FromHexString(associatedData))
                .Should().BeFalse($"the specification requires this vector to fail (software={software})");
            plaintext.Should().OnlyContain(value => value == 0, "unverified plaintext must never be released");
        }
    }

    /// <summary>Ahtola only produces 128-bit AEGIS tags, matching Turso's instantiation.</summary>
    [TestCase(StorageCipher.Aegis256)]
    [TestCase(StorageCipher.Aegis128L)]
    public void AegisRejectsTagSizesOtherThanSixteenBytes(StorageCipher cipher)
    {
        var parameters = AhtolaEncryptedPageFormat.GetParameters(cipher);
        using var aead = AhtolaAeadFactory.Create(cipher, new byte[parameters.KeySize]);
        Assert.Throws<ArgumentException>(
            () => aead.Encrypt(new byte[parameters.NonceSize], [], [], new byte[32], []));
    }

    /// <summary>
    /// AEGIS-128X and AEGIS-256X at degree 1 are defined to equal AEGIS-128L and
    /// AEGIS-256, so a random differential across degrees would be meaningless if
    /// the context separator were applied wrongly. This pins the reduction.
    /// </summary>
    [Test]
    public void ParallelDegreesProduceDistinctCiphertextsFromTheirBaseCipher()
    {
        var message = new byte[512];
        RandomNumberGenerator.Fill(message);

        var aegis128 = EncryptWith(StorageCipher.Aegis128L, ParallelKey128, ParallelNonce128, message);
        var aegis128X2 = EncryptWith(StorageCipher.Aegis128X2, ParallelKey128, ParallelNonce128, message);
        var aegis128X4 = EncryptWith(StorageCipher.Aegis128X4, ParallelKey128, ParallelNonce128, message);
        aegis128.Should().NotEqual(aegis128X2);
        aegis128.Should().NotEqual(aegis128X4);
        aegis128X2.Should().NotEqual(aegis128X4);

        var aegis256 = EncryptWith(StorageCipher.Aegis256, ParallelKey256, ParallelNonce256, message);
        var aegis256X2 = EncryptWith(StorageCipher.Aegis256X2, ParallelKey256, ParallelNonce256, message);
        var aegis256X4 = EncryptWith(StorageCipher.Aegis256X4, ParallelKey256, ParallelNonce256, message);
        aegis256.Should().NotEqual(aegis256X2);
        aegis256.Should().NotEqual(aegis256X4);
        aegis256X2.Should().NotEqual(aegis256X4);
    }

    private static byte[] EncryptWith(
        StorageCipher cipher,
        string key,
        string nonce,
        ReadOnlySpan<byte> message)
    {
        using var aead = AhtolaAeadFactory.Create(cipher, Convert.FromHexString(key));
        var output = new byte[message.Length + 16];
        aead.Encrypt(
            Convert.FromHexString(nonce),
            message,
            output.AsSpan(0, message.Length),
            output.AsSpan(message.Length, 16),
            []);
        return output;
    }

    private static byte[] ToArray(System.Runtime.Intrinsics.Vector128<byte> value)
    {
        var bytes = new byte[16];
        System.Runtime.Intrinsics.Vector128.CopyTo(value, bytes.AsSpan());
        return bytes;
    }


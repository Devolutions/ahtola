    /// <summary>
    /// The <c>AESRound</c> test vector from the specification appendix. This is
    /// the primitive every AEGIS variant is built from, so pinning it isolates a
    /// bad round function from a bad mode.
    /// </summary>
    [Test]
    public void AesRoundMatchesSpecificationVector()
    {
        var input = System.Runtime.Intrinsics.Vector128.Create<byte>(
            Convert.FromHexString("000102030405060708090a0b0c0d0e0f"));
        var roundKey = System.Runtime.Intrinsics.Vector128.Create<byte>(
            Convert.FromHexString("101112131415161718191a1b1c1d1e1f"));
        var expected = Convert.FromHexString("7a7b4e5638782546a8c0477a3b813f43");

        ToArray(AhtolaAesRound.Encrypt(input, roundKey)).Should().Equal(expected);
        ToArray(AhtolaAesRound.EncryptSoftware(input, roundKey)).Should().Equal(expected);
    }

    /// <summary>The bit-matrix transpose used by the software round is self-inverse and correct.</summary>
    [Test]
    public void SoftwareRoundBitTransposeMatchesNaiveTransposition()
    {
        var random = new Random(20260823);
        Span<byte> buffer = stackalloc byte[8];
        for (var iteration = 0; iteration < 256; iteration++)
        {
            random.NextBytes(buffer);
            var value = System.Buffers.Binary.BinaryPrimitives.ReadUInt64LittleEndian(buffer);

            ulong expected = 0;
            for (var i = 0; i < 8; i++)
            {
                for (var j = 0; j < 8; j++)
                {
                    var bit = (value >> ((i * 8) + j)) & 1UL;
                    expected |= bit << ((j * 8) + i);
                }
            }

            AhtolaAesRound.Transpose8(value).Should().Be(expected);
            AhtolaAesRound.Transpose8(AhtolaAesRound.Transpose8(value)).Should().Be(value);
        }
    }

    /// <summary>The software round must agree with the hardware round on random inputs.</summary>
    [Test]
    public void SoftwareAesRoundMatchesAcceleratedAesRound()
    {
        if (!AhtolaAesRound.IsHardwareAccelerated)
            Assert.Ignore("This CPU has no AES round instruction; the software round is already the only path.");

        var random = new Random(20260824);
        Span<byte> state = stackalloc byte[16];
        Span<byte> roundKey = stackalloc byte[16];
        for (var iteration = 0; iteration < 512; iteration++)
        {
            random.NextBytes(state);
            random.NextBytes(roundKey);
            var s = System.Runtime.Intrinsics.Vector128.Create<byte>(state);
            var k = System.Runtime.Intrinsics.Vector128.Create<byte>(roundKey);
            ToArray(AhtolaAesRound.EncryptSoftware(s, k)).Should().Equal(ToArray(AhtolaAesRound.Encrypt(s, k)));
        }
    }


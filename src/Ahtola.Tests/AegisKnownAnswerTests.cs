    [TestCaseSource(nameof(Aegis128LVectors))]
    [TestCaseSource(nameof(Aegis256Vectors))]
    [TestCaseSource(nameof(AegisParallelVectors))]
    public void AegisEncryptMatchesSpecificationVector(AegisVector vector)
    {
        foreach (var software in new[] { false, true })
        {
            using var aead = AhtolaAeadFactory.Create(vector.Cipher, vector.Key, software);
            var ciphertext = new byte[vector.Message.Length];
            var tag = new byte[16];
            aead.Encrypt(vector.Nonce, vector.Message, ciphertext, tag, vector.AssociatedData);

            ciphertext.Should().Equal(vector.Ciphertext, $"{vector.Name} ciphertext (software={software})");
            tag.Should().Equal(vector.Tag, $"{vector.Name} tag (software={software})");
        }
    }

    [TestCaseSource(nameof(Aegis128LVectors))]
    [TestCaseSource(nameof(Aegis256Vectors))]
    [TestCaseSource(nameof(AegisParallelVectors))]
    public void AegisDecryptRecoversSpecificationVector(AegisVector vector)
    {
        foreach (var software in new[] { false, true })
        {
            using var aead = AhtolaAeadFactory.Create(vector.Cipher, vector.Key, software);
            var plaintext = new byte[vector.Ciphertext.Length];
            aead.TryDecrypt(vector.Nonce, vector.Ciphertext, vector.Tag, plaintext, vector.AssociatedData)
                .Should().BeTrue($"{vector.Name} must authenticate (software={software})");
            plaintext.Should().Equal(vector.Message, $"{vector.Name} plaintext (software={software})");
        }
    }

